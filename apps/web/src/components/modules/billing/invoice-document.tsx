"use client";

import { Printer, Receipt } from "lucide-react";
import type { InvoiceRow } from "@medcore/types";
import { Button } from "@/components/ui/button";
import { Dialog, DialogContent, DialogDescription, DialogHeader, DialogTitle, DialogTrigger } from "@/components/ui/dialog";
import { LogoMark } from "@/components/logo";
import { InvoiceStatusBadge } from "@/components/dashboard/status-badge";
import { useHospitalName } from "@/hooks/use-session";
import { formatCurrency, formatDate } from "@/lib/format";

const CATEGORY = { CONSULTATION: "Consultation", LAB: "Laboratory", PHARMACY: "Pharmacy", ROOM: "Room", PROCEDURE: "Procedure" } as const;

/** Printable invoice; once paid it doubles as the receipt. */
export function InvoiceDialog({ invoice, trigger }: { invoice: InvoiceRow; trigger?: React.ReactNode }) {
  const isReceipt = invoice.status === "PAID";
  const due = Math.max(0, invoice.total - invoice.paid);
  const hospitalName = useHospitalName();
  return (
    <Dialog>
      <DialogTrigger asChild>
        {trigger ?? (
          <Button size="sm" variant="ghost">
            <Receipt /> View
          </Button>
        )}
      </DialogTrigger>
      <DialogContent className="max-w-2xl">
        <DialogHeader>
          <DialogTitle>
            {isReceipt ? "Receipt" : "Invoice"} {invoice.number}
          </DialogTitle>
          <DialogDescription>Print or choose &quot;Save as PDF&quot; in the print dialog.</DialogDescription>
        </DialogHeader>
        <div className="print-area overflow-x-auto rounded-lg border bg-white p-6 text-sm text-slate-900">
          <div className="flex items-start justify-between border-b border-slate-200 pb-4">
            <div className="flex items-center gap-3">
              <LogoMark />
              <div>
                <p className="font-display text-lg font-bold">{hospitalName}</p>
                <p className="text-xs text-slate-500">{isReceipt ? "Payment receipt" : "Tax invoice"}</p>
              </div>
            </div>
            <div className="text-right text-xs">
              <p className="font-semibold">{invoice.number}</p>
              <p className="text-slate-500">Issued {formatDate(invoice.issuedAt)}</p>
              <p className="text-slate-500">Due {formatDate(invoice.dueAt)}</p>
            </div>
          </div>
          <p className="py-3">
            <span className="text-slate-500">Billed to: </span>
            <span className="font-medium">{invoice.patientName}</span>
          </p>
          <table className="w-full">
            <thead className="border-y border-slate-200 text-xs text-slate-500">
              <tr>
                <th className="py-2 text-left font-medium">Description</th>
                <th className="py-2 text-right font-medium">Qty</th>
                <th className="py-2 text-right font-medium">Rate</th>
                <th className="py-2 text-right font-medium">Tax</th>
                <th className="py-2 text-right font-medium">Amount</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100">
              {invoice.items.map((i, n) => (
                <tr key={n}>
                  <td className="py-2">
                    {i.description}
                    <span className="block text-xs text-slate-500">{CATEGORY[i.category]}</span>
                  </td>
                  <td className="py-2 text-right tabular-nums">{i.quantity}</td>
                  <td className="py-2 text-right tabular-nums">{formatCurrency(i.unitPrice, true)}</td>
                  <td className="py-2 text-right tabular-nums">{i.taxRate}%</td>
                  <td className="py-2 text-right tabular-nums">{formatCurrency(i.quantity * i.unitPrice, true)}</td>
                </tr>
              ))}
            </tbody>
          </table>
          <dl className="mt-4 ml-auto grid w-64 gap-1 tabular-nums">
            <div className="flex justify-between"><dt className="text-slate-500">Subtotal</dt><dd>{formatCurrency(invoice.subtotal, true)}</dd></div>
            <div className="flex justify-between"><dt className="text-slate-500">Tax (GST)</dt><dd>{formatCurrency(invoice.tax, true)}</dd></div>
            <div className="flex justify-between border-t border-slate-200 pt-1 font-semibold"><dt>Total</dt><dd>{formatCurrency(invoice.total, true)}</dd></div>
            <div className="flex justify-between"><dt className="text-slate-500">Paid{invoice.lastPaymentMethod ? ` (${invoice.lastPaymentMethod})` : ""}</dt><dd>{formatCurrency(invoice.paid, true)}</dd></div>
            <div className="flex justify-between font-semibold"><dt>Balance due</dt><dd>{formatCurrency(due, true)}</dd></div>
          </dl>
          <p className="mt-8 text-[10px] text-slate-400">Generated by MedCore HMS. Academic project — not a valid tax document.</p>
        </div>
        <div className="flex items-center justify-between">
          <InvoiceStatusBadge status={invoice.status} />
          <Button onClick={() => window.print()}>
            <Printer /> Print / Save as PDF
          </Button>
        </div>
      </DialogContent>
    </Dialog>
  );
}
